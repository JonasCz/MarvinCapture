import SwiftUI

/// Shown instead of the UI when the startup probe fails.
struct StartupErrorView: View {
    let message: String

    var body: some View {
        VStack(spacing: 16) {
            Image(systemName: "exclamationmark.triangle.fill")
                .font(.system(size: 40)).foregroundStyle(.orange)
            Text("MarvinCapture cannot start").font(.title2.bold())
            Text(message).textSelection(.enabled).multilineTextAlignment(.leading)
        }
        .padding(32)
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }
}
